type GetDigitAdd<D1 extends string, D2 extends string, C extends Carry> =
  D1 extends Digit
    ? D2 extends Digit
      ? SingleDigitAddMap[D1][D2][C]
      : ['0', '0']
    : ['0', '0'];

// simple recursive string reverse
export type Reverse<S extends string, Acc extends string = ''> =
  S extends `${infer Head}${infer Tail}`
    ? Reverse<Tail, `${Head}${Acc}`>
    : Acc;

export type TrimLeadingZeros<S extends string> =
  S extends `0${infer Rest}`
    ? Rest extends ''
      ? '0'
      : TrimLeadingZeros<Rest>
    : S;

// elementary level addition
// go from least to most significant digit and add while tracking carry
type AddReversed<
  A extends string,
  B extends string,
  C extends Carry = '0'
> = A extends `${infer HeadA}${infer TailA}`
  ? B extends `${infer HeadB}${infer TailB}`
    ? GetDigitAdd<HeadA, HeadB, C> extends [infer Res extends string, infer NextC extends Carry]
      ? `${Res}${AddReversed<TailA, TailB, NextC>}`
      : never
    : AddReversed<A, '0', C>
  : B extends `${infer _HeadB}${infer _TailB}`
    ? AddReversed<'0', B, C>
    : C extends '1'
      ? '1'
      : '';

// Addition type
export type Add<A extends string, B extends string> = TrimLeadingZeros<
  Reverse<AddReversed<Reverse<A>, Reverse<B>, '0'>>
>;

type Equal<X, Y> = (<T>() => T extends X ? 1 : 2) extends (<T>() => T extends Y ? 1 : 2) ? true : false;
type Assert<T extends true> = T;

type OddDigits = "1" | "3" | "5" | "7" | "9"

type Odd<T extends string> = Reverse<T> extends `${infer _D extends OddDigits}${infer _Rest}` ? T 
						   : T extends OddDigits ? T
						   : "0"

type OddInput<T extends string[]> = T extends [infer H extends string, ...infer Rest extends string[]]
								  ? [Odd<H>, ...OddInput<Rest>]
								  : []

type Sum<T extends string[], acc extends string = "0"> = 
	T extends [infer H extends string, ...infer Rest extends string[]] ? Sum<Rest, Add<acc, H>>
	: acc

